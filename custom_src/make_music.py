# Music of the custom variant (decided by the user, 2026-11-19, lists in Documentation/Musik-Auswahl.md and Musik-FO2.md).
#   python custom_src/make_music.py <extracted original foucpack_gcp_music.bfs (folder with data/music)>
# Writes:
#   custom_src/music_remove.txt              loose song files that build.ps1 does not copy (from the marked rows)
#   custom_src/music_overrides/data/music/   playlists without the removed songs + combined playlists
#   custom_src/config_overrides/Config/Music.toml
# Playlists kept: FO1, FO2, FOUC, MODERN (+ FO2 + UC). Removed: FOREIGN, RALLY, STUNT SHOW, per-track songs of addon tracks.
# New default playlist "FO1, FO2, FOUC, MODERN" (race and menu) = all songs of the kept playlists.
import os, re, sys

here = os.path.dirname(os.path.abspath(__file__))
root = os.path.dirname(here)
src = os.path.join(sys.argv[1], 'data', 'music')
out = os.path.join(here, 'music_overrides', 'data', 'music')
os.makedirs(out, exist_ok=True)

# --- removed files = rows marked with x in the first column of both lists ---------------------------------
removed = []
for name in ['Musik-Auswahl.md', 'Musik-FO2.md']:
    for line in open(os.path.join(root, 'Documentation', name), encoding='utf-8-sig'):
        cells = [c.strip() for c in line.strip().split('|')]
        if len(cells) < 7 or not cells[6].startswith('['):
            continue
        if cells[1].lower() == 'x':
            removed.append(re.match(r'\[(.*)\]\(', cells[6]).group(1))
removed_set = {r.lower() for r in removed}
with open(os.path.join(here, 'music_remove.txt'), 'w', encoding='utf-8', newline='\n') as f:
    f.write('# loose files in Data/music that build.ps1 does not copy (generated by make_music.py)\n')
    for r in sorted(removed, key=str.lower):
        f.write(r + '\n')

# --- playlists ------------------------------------------------------------------------------------------------
def read_playlist(name):
    t = open(os.path.join(src, name + '.bed'), 'rb').read().decode('latin-1')
    entries = []
    for m in re.finditer(r'\[\d+\]\s*=\s*\{(.*?)\}', t, re.S):
        fields = re.findall(r'(\w+)\s*=\s*("(?:[^"\\]|\\.)*"|[^,\r\n]+)\s*,', m.group(1))
        entries.append([(k, v.strip()) for k, v in fields])
    return entries

def file_of(entry):
    return dict(entry)['File'].strip('"').lower()

def write_playlist(name, entries):
    lines = ['Loop\t= {', '\tCount = %d,' % len(entries)]
    for i, e in enumerate(entries, 1):
        lines.append('\t[%d] = {' % i)
        for k, v in e:
            lines.append('\t\t%s\t= %s,' % (k, v))
        lines.append('\t},')
    lines.append('}')
    open(os.path.join(out, name + '.bed'), 'wb').write(('\r\n'.join(lines) + '\r\n').encode('latin-1'))

def without_removed(entries):
    return [e for e in entries if file_of(e).replace('data/music/', '') not in removed_set]

kept = {}
for name in ['playlist_ingame', 'playlist_ingamefo2', 'playlist_ingamefouc', 'playlist_ingamefo1', 'playlist_ingamemodern',
             'playlist_ingamemodern2', 'playlist_title', 'playlist_titlefo2', 'playlist_titlefouc', 'playlist_titlefo1',
             'playlist_titlemodern']:
    original = read_playlist(name)
    kept[name] = without_removed(original)
    if len(kept[name]) != len(original):
        write_playlist(name, kept[name])
        print('%s: %d -> %d songs' % (name, len(original), len(kept[name])))

def combined(names):
    seen, result = set(), []
    for n in names:
        for e in kept[n]:
            if file_of(e) not in seen:
                seen.add(file_of(e)); result.append(e)
    return result

race = combined(['playlist_ingame', 'playlist_ingamefo1', 'playlist_ingamemodern'])
menu = combined(['playlist_title', 'playlist_titlefo1', 'playlist_titlemodern'])
write_playlist('playlist_ingamecombined', race)
write_playlist('playlist_titlecombined', menu)
print('combined: race %d songs, menu %d songs' % (len(race), len(menu)))

# --- Music.toml (Chloe's soundtrack swapper, source/FlatOutUCChloeCollection/soundtrackswapper.h) ----------------
COMBINED = 'FO1, FO2, FOUC, MODERN'
race_lists = [(COMBINED, 'playlist_ingamecombined'), ('FLATOUT 2 + UC', 'playlist_ingame'), ('FLATOUT 2', 'playlist_ingamefo2'),
              ('FLATOUT UC', 'playlist_ingamefouc'), ('FLATOUT 1', 'playlist_ingamefo1'), ('MODERN', 'playlist_ingamemodern')]
menu_lists = [(COMBINED, 'playlist_titlecombined'), ('FLATOUT 2 + UC', 'playlist_title'), ('FLATOUT 2', 'playlist_titlefo2'),
              ('FLATOUT UC', 'playlist_titlefouc'), ('FLATOUT 1', 'playlist_titlefo1'), ('MODERN', 'playlist_titlemodern')]
toml = ['# Music playlist data', '# ChloeCustom: generated by custom_src/make_music.py.',
        '# FOREIGN, RALLY and STUNT SHOW removed, new default "%s" (all songs of the remaining playlists).' % COMBINED,
        '# Settings in Savegame/options.cfg are 0-based indexes into these lists.', '',
        '[main]', 'playlist_count=%d' % len(race_lists), 'menuplaylist_count=%d' % len(menu_lists), 'stuntplaylist_count=2',
        'default_menu=1', 'default_race=1', 'default_fo1_race=5', 'default_tt_race=5', 'default_rt_race=1',
        'default_arcade_race=1', 'default_derby=1', 'default_frag_derby=1', 'default_stunt=2', 'default_stuntshow=1',
        'default_drift=1', '']
for i, (n, f) in enumerate(race_lists, 1):
    toml += ['[playlist%d]' % i, 'name="%s"' % n, 'file="%s"' % f, '']
for i, (n, f) in enumerate(menu_lists, 1):
    toml += ['[menuplaylist%d]' % i, 'name="%s"' % n, 'file="%s"' % f, '']
toml += ['[stuntplaylist1]', 'name="FLATOUT UC"', 'file="playlist_stunt"', '',
         '[stuntplaylist2]', 'name="FLATOUT 2"', 'file="playlist_stuntfo2"', '']
open(os.path.join(here, 'config_overrides', 'Config', 'Music.toml'), 'w', encoding='utf-8', newline='\n').write('\n'.join(toml))
print('removed files: %d' % len(removed))
